function state(row: Row, current: boolean): ProjectState {
  const [
    id,
    contract,
    oldPaid,
    paid,
    oldProgress,
    progress,
    target,
    oldDelivered,
    delivered,
    unit,
    status,
  ] = row;
  const snapshotId = current ? "sep-2026" : "aug-2026";
  const date = current ? "2026-09-30" : "2026-08-31";
  function fact<T extends string | number>(
    field: string,
    value: T | null,
    unit = "",
    documentType = "Raport de implementare fictiv",
  ): Fact<T> {
    const sourceId = `${snapshotId}-${id}-${field}-source`;
    registerSource({
      id: sourceId,
      title: `${documentType} · ${id} · ${field}`,
      type: documentType,
      date,
      description: `Document simulat pentru câmpul „${field}”. Valoarea ${value === null ? "lipsește din scenariu" : `este ${value}${unit ? ` ${unit}` : ""}`}. Nu reprezintă un document public real.`,
      isDemo: true,
    });
    return {
      id: `${snapshotId}-${id}-${field}`,
      value,
      unit,
      referenceDate:
        id === "comunitate-bc" || id === "mediu-vn" ? "2026-07-31" : date,
      provenance:
        field === "contracted" || field === "deadline"
          ? "extras din document"
          : "raportat oficial",
      sourceIds: [sourceId],
      isDemo: true,
    };
  }
  return {
    projectId: id,
    snapshotId,
    currency: "RON",
    vat: "inclus",
    contracted: fact(
      "contracted",
      !current && id === "energie-bc" ? 4000000 : contract,
      "RON",
      "Contract / act adițional fictiv",
    ),
    paid: fact("paid", current ? paid : oldPaid, "RON"),
    progress: fact("progress", current ? progress : oldProgress, "%"),
    deadline: fact(
      "deadline",
      id === "transport-bc" ? "2026-09-15" : "2026-12-15",
    ),
    status: fact<Status>(
      "status",
      !current && (status === "finalizat" || status === "intarziat")
        ? "in-lucru"
        : status,
    ),
    promised: fact("promised", target, unit),
    delivered: fact("delivered", current ? delivered : oldDelivered, unit),
    outcome: fact<string>("outcome", null),
    delayEvidence: fact<string>(
      "delay-evidence",
      current && id === "transport-bc"
        ? "Nota de monitorizare demo din 30 septembrie confirmă depășirea termenului de recepție din 15 septembrie. Niciun autobuz nu era recepționat."
        : null,
      "",
      "Notă de monitorizare fictivă",
    ),
  };
}
